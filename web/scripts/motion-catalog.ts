// Writes the Gymix motion library into the exercises catalog as a migration.
// Usage (from web/): npx tsx scripts/motion-catalog.ts [migration file name]
// Re-run after changing src/lib/motion/library.ts and commit the new migration.
import { writeFileSync } from "node:fs";
import { catalogRows } from "../src/lib/motion/catalog";

const name = process.argv[2] ?? "20261115090000_motion_library.sql";
const out = new URL(`../../supabase/migrations/${name}`, import.meta.url);

const str = (v: string | null) => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);
const arr = (a: string[]) => (a.length ? `array[${a.map(str).join(", ")}]` : "'{}'") + "::text[]";

const rows = catalogRows();
const values = rows.map(
  (r) =>
    `(${[
      str(r.id),
      str(r.name),
      str(r.category),
      str(r.equipment),
      str(r.level),
      str(r.force),
      str(r.mechanic),
      arr(r.primary_muscles),
      arr(r.secondary_muscles),
      arr(r.instructions),
      arr(r.image_paths),
      str(r.source),
    ].join(", ")})`,
);

const sql = `-- Generated by web/scripts/motion-catalog.ts from web/src/lib/motion/library.ts; do not edit by hand.
-- The Gymix motion library: ${rows.length} exercises, each animated by the motion engine
-- (image_paths = 'motion:<id>' is played by ExerciseAnimation instead of photos).
insert into public.exercises
  (id, name, category, equipment, level, force, mechanic, primary_muscles, secondary_muscles, instructions, image_paths, source)
values
${values.join(",\n")}
on conflict (id) do update set
  name = excluded.name, category = excluded.category, equipment = excluded.equipment, level = excluded.level,
  force = excluded.force, mechanic = excluded.mechanic, primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles, instructions = excluded.instructions,
  image_paths = excluded.image_paths, source = excluded.source;

-- Exercises dropped from the library since an earlier version, unless something still uses them.
delete from public.exercises e
 where e.source = 'gymix-motion'
   and e.id <> all (array[${rows.map((r) => str(r.id)).join(", ")}]::text[])
   and not exists (select 1 from public.machine_exercises me where me.exercise_id = e.id)
   and not exists (select 1 from public.program_exercises pe where pe.exercise_id = e.id)
   and not exists (select 1 from public.workout_exercises we where we.exercise_id = e.id)
   and not exists (select 1 from public.set_logs sl where sl.exercise_id = e.id);
`;

writeFileSync(out, sql);
console.log(`${rows.length} exercises -> supabase/migrations/${name}`);
