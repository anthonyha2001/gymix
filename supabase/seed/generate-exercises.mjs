// Builds supabase/seed.sql from free-exercise-db (public domain, https://github.com/yuhonas/free-exercise-db).
// Usage (from repo root): node supabase/seed/generate-exercises.mjs [path-or-url-to-exercises.json]
// `supabase db reset` runs the generated seed.sql automatically.
import { readFile, writeFile } from "node:fs/promises";

const SOURCE = process.argv[2] ?? "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json";
const OUT = new URL("../seed.sql", import.meta.url);

const raw = SOURCE.startsWith("http") ? await (await fetch(SOURCE)).text() : await readFile(SOURCE, "utf8");
const exercises = JSON.parse(raw);

const str = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => (a?.length ? `array[${a.map(str).join(", ")}]` : "'{}'") + "::text[]";

const rows = exercises.map(
  (e) =>
    `(${[
      str(e.id),
      str(e.name),
      str(e.category),
      str(e.equipment),
      str(e.level),
      str(e.force),
      str(e.mechanic),
      arr(e.primaryMuscles),
      arr(e.secondaryMuscles),
      arr(e.instructions),
      arr(e.images),
    ].join(", ")})`,
);

const sql = `-- Generated by supabase/seed/generate-exercises.mjs — do not edit by hand.
-- Exercise library from free-exercise-db (public domain / Unlicense): ${exercises.length} exercises.
insert into public.exercises
  (id, name, category, equipment, level, force, mechanic, primary_muscles, secondary_muscles, instructions, image_paths)
values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name, category = excluded.category, equipment = excluded.equipment, level = excluded.level,
  force = excluded.force, mechanic = excluded.mechanic, primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles, instructions = excluded.instructions,
  image_paths = excluded.image_paths;
`;

await writeFile(OUT, sql);
console.log(`Wrote ${exercises.length} exercises to ${OUT.pathname}`);
